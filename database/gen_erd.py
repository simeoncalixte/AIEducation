"""Generate docs/data-model.md with a Mermaid ERD from the live metadata.

Run from database/:  .venv/bin/python gen_erd.py

The diagram derives tables, columns, keys, and relationships from
DataModels.Base.metadata, so it cannot drift from the models. Do not hand-edit
the generated file; change the models and re-run.
"""

import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

from sqlalchemy import REAL, Boolean, DateTime, Enum, Integer, String, Text

import DataModels as m  # noqa: E402

HEADER = """# Data model (ERD)

Source of truth for keys and relationships, generated from
`database/DataModels.py` by `database/gen_erd.py` — do not hand-edit this
diagram. Per-table detail (fields, rules, prose) lives in
[entities/](entities/README.md).

## Viewing

- GitHub renders the diagram inline below.
- VS Code: any Mermaid preview extension.
- Otherwise paste the `mermaid` block into a Mermaid renderer.

## Conventions

- `PK` / `FK` markers on key columns; `*` lines are foreign-key references.
- `||--o{` mandatory reference, `|o--o{` nullable reference; the label is the
  referencing column (minus `_id`).
- Table and column names match the database exactly.

```mermaid
%% Generated by database/gen_erd.py — do not hand-edit.
erDiagram
"""


def coltype(column):
    t = column.type
    if isinstance(t, Enum):
        return t.enum_class.__name__ if t.enum_class else "enum"
    if isinstance(t, Integer):
        return "int"
    if isinstance(t, String):
        return "string"
    if isinstance(t, Text):
        return "text"
    if isinstance(t, Boolean):
        return "bool"
    if isinstance(t, REAL):
        return "real"
    if isinstance(t, DateTime):
        return "timestamptz"
    if "JSON" in type(t).__name__:
        return "json"
    return "string"


def main():
    lines = [HEADER.rstrip("\n")]
    tables = sorted(m.Base.metadata.tables.values(), key=lambda t: t.name)
    for table in tables:
        lines.append(f"    {table.name} {{")
        for col in table.columns:
            marker = ""
            if col.primary_key:
                marker = " PK"
            elif col.foreign_keys:
                marker = " FK"
            lines.append(f"        {coltype(col)} {col.name}{marker}")
        lines.append("    }")
    for table in tables:
        for col in table.columns:
            for fk in sorted(col.foreign_keys, key=lambda f: f.target_fullname):
                parent = fk.column.table.name
                left = "|o" if col.nullable else "||"
                label = col.name[:-3] if col.name.endswith("_id") else col.name
                lines.append(
                    f"    {parent} {left}--o{{ {table.name} : \"{label}\""
                )
    lines.append("```")
    out = os.path.join(
        os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
        "docs",
        "data-model.md",
    )
    with open(out, "w") as fh:
        fh.write("\n".join(lines) + "\n")
    print(f"wrote {out} ({len(tables)} tables)")


if __name__ == "__main__":
    main()
